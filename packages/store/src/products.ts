import { PRODUCT_OPTIONS } from './product-options';
import type { ProductFormInput, ProductOptionInput } from './product-record';

/**
 * 상품 옵션 시드를 폼 입력 형태로 옮긴다.
 * 판매 화면(`lib/data/product-options.ts`)과 등록 폼이 **같은 옵션**을 보게 하기 위해서다.
 */
function optionsOf(productId: string): {
  colors: string[];
  sizes: string[];
  options: ProductOptionInput[];
} {
  const rows = PRODUCT_OPTIONS.filter((option) => option.productId === productId);
  return {
    colors: [...new Set(rows.map((option) => option.color))],
    sizes: [...new Set(rows.map((option) => option.size))].filter(Boolean),
    options: rows.map((option) => ({
      key: `${option.color}|${option.size}`,
      color: option.color,
      size: option.size,
      stock: `${option.stock}`,
    })),
  };
}

