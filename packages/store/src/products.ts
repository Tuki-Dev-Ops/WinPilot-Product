export function findProduct(id: string): ProductRecord | undefined {
  return PRODUCTS.find((product) => product.id === id);
}

/** 상품 코드는 사람이 정하지 않는다 — 등록 화면에 자동 생성된 값을 보여 준다. */
export function nextProductCode(products: ProductRecord[] = PRODUCTS): string {
  const max = products.reduce((biggest, product) => Math.max(biggest, Number(product.id.replace('P-', ''))), 1000);
  return `P-${max + 1}`;
}
