/**
 * B. 픽셀 검증 — 글리프 안티에일리어싱 잔차만 허용한다.
 *
 * Chromium(Skia) 과 Figma 는 서로 다른 텍스트 래스터라이저를 쓰므로
 * 글리프 가장자리의 서브픽셀 명암 차이는 제거할 수 없다. 그 예외가 구멍이 되지 않도록
 * 아래 세 지표로 "정말 AA 차이일 뿐인지" 를 정량 검사한다.
 */
/**
 * 아래 임계값은 **추측이 아니라 측정으로 잡았다.** `pnpm ssot:selftest` 가 실제 baseline 에
 * 합성 변형을 가해 각 지표가 어떻게 반응하는지 재고, 그 분리도를 근거로 정한다.
 *
 * 측정값 (1440×1867 스캐폴드 페이지, 줄 214개):
 *
 * | 변형              | 무게중심 최대 | 커버리지 최대 |
 * |-------------------|--------------|--------------|
 * | AA 잔차 ±3        | 0.089 px     | 0.9 %        |
 * | AA 잔차 ±6        | 0.178 px     | 1.8 %        |
 * | 0.5px 이동        | 0.757 px     | 0.7 %        |
 * | 1px 이동          | 1.000 px     | 1.1 %        |
 *
 * 읽어야 할 것 두 가지:
 *  - **무게중심은 깨끗하게 갈린다** (AA ≤0.18 / 실제 이동 ≥0.76). 4배 이상 벌어진다.
 *  - **커버리지는 갈리지 않는다.** 순수 AA 노이즈가 실제 이동보다 오히려 커버리지를 더 흔든다.
 *    커버리지를 촘촘히 조이면 AA 만 있는 정상 케이스를 떨어뜨리고 진짜 이동은 놓친다.
 *    그래서 커버리지는 '미세 이동 탐지'가 아니라 **색·굵기 이상 탐지** 로만 쓰고 임계를 크게 잡는다.
 *
 * ⚠️ 이 값들은 합성 AA 노이즈 기준이다. 실제 Figma 출력을 받으면 재보정해야 한다.
 */
export const PIXEL_TOLERANCE = {
  /** 잉크 마스크를 이만큼 팽창시킨 영역 '밖'은 diff 가 1픽셀이라도 있으면 FAIL */
  aaMaskDilationPx: 1,

  /**
   * 줄 단위 잉크 커버리지 합의 상대 차이 상한.
   *
   * 잡는 대상은 **색·굵기 이상**이다 (400→700, 글자색 오적용 등은 20% 이상 변한다).
   * 서브픽셀 이동 탐지는 무게중심이 담당하므로 여기를 조일 이유가 없다.
   */
  inkCoverageRatio: 0.05,

  /**
   * 줄 단위 잉크 무게중심 편차 상한 (x, y 각각, px).
   *
   * 이 설계의 핵심 장치다. 순수한 AA 차이는 경계 픽셀 명암이 양쪽으로 상쇄되어
   * 무게중심을 거의 움직이지 못하지만, 글자가 밀리거나 폰트가 대체되면 즉시 이 임계를 넘는다.
   * 0.35 는 측정된 AA 최댓값(0.18)의 약 2배이자 0.5px 이동(0.76)의 절반 — 양쪽으로 여유가 있다.
   */
  inkCentroidPx: 0.35,

  /** 줄 단위 잉크 바운딩박스 편차 상한 (px) — 줄바꿈·자간 이상을 잡는다 */
  inkBoundsPx: 1,
} as const;

