import type { ReactNode } from 'react';

/**
 * 화면 머리 — 이름 한 마디와 설명 한 줄. **두 어드민이 같은 것을 쓴다.**
 *
 * 툴바 바로 위에 선다. 탭·검색·등록이 무엇을 *할 수 있는지*를 말한다면 여기는 **이 화면이
 * 무엇을 하는 곳인지**를 말한다. 그것이 없으면 처음 들어온 사람은 탭 이름들을 읽어 가며
 * 화면의 용도를 거꾸로 짐작해야 한다.
 *
 * ## 셸 헤더의 경로 표시와 겹치는 문제
 * 두 어드민의 셸은 위쪽에 `고객사 | 고객` 같은 **경로**를 이미 그린다. 마지막 마디가 여기
 * `title` 과 같은 말이 되므로 한 화면에 같은 단어가 두 번 나온다. 그래도 둘을 남긴 이유:
 *
 * - 경로는 **어디에 있나**에 답한다. 갈래(부모)까지 함께 보여 주므로 여기 이름만으로는 대신할 수 없다.
 * - 머리는 **이 화면이 무엇을 하나**에 답한다. 설명 한 줄이 붙는 자리는 여기뿐이다.
 *
 * 대신 **제목을 `h1` 로 두지 않는다.** 셸 헤더가 이미 `h1` 이라, 여기까지 `h1` 이면 한 문서에
 * 최상위 제목이 둘이 되어 화면 낭독기가 어느 쪽이 이 화면의 이름인지 알 수 없다.
 *
 * ## 쓰는 말
 * `title` 은 **메뉴에 적힌 것과 같은 말**을 쓴다. 다르면 메뉴에서 누른 것과 열린 화면이 다른
 * 것처럼 읽힌다.
 *
 * `description` 은 **한 문장, 마침표 하나**이고 **`~하세요` 체**다. 화면에 보이는 글은 읽는
 * 사람에게 건네는 말이라, 평서형(`~한다`)으로 두면 설명서가 아니라 메모처럼 읽힌다. 기능을
 * 나열하지도 않는다 — 바로 아래 탭·단추가 같은 말을 다시 하게 된다.
 *
 * 이 주석이 `~한다` 체인 것은 반대 이유에서다. 만드는 사람끼리 규칙을 못 박는 글이라
 * 건네는 말투로 쓰면 근거가 권유처럼 읽힌다.
 */
export function PageHeading({
  title,
  description,
  aside,
}: {
  title: string;
  description: string;
  /**
   * 제목 오른쪽에 서는 것 — 기간 고르개처럼 **이 화면 전체에 걸리는** 조작.
   *
   * 이 자리를 여기 둔 이유: 전에는 화면이 머리와 조작을 나란히 놓고 싶을 때 바깥에 줄을 하나
   * 더 만들어 감쌌는데, 그러면 **아래 선이 제목 밑에서만 그어지다 만다** — 선은 이 조각 안에
   * 있고 조각은 제목 너비만큼만 차지하기 때문이다. 화면마다 그 어긋남을 따로 고치느니
   * 여기서 한 줄로 받는다.
   *
   * 목록 위 툴바(검색 · 등록)는 여기 오지 않는다. 그것은 **표에 걸리는** 조작이라 표 옆에 선다.
   */
  aside?: ReactNode;
}) {
  return (
    <div className="flex flex-wrap items-end justify-between gap-4 border-b border-border pb-4">
      <div className="flex min-w-0 flex-col gap-1">
        <h2 className="text-xl font-semibold tracking-tight">{title}</h2>
        <p className="text-sm leading-relaxed text-ink-muted">{description}</p>
      </div>
      {aside}
    </div>
  );
}
