/**
 * **Back-End 요구사항 정의** — 실제 서버는 만들지 않되, 만들 수 있게 적는다.
 *
 * ## 왜 정의는 하는가
 * 이 과업에 서버가 없다고 해서 Back-End 절을 비워 두면, 뒤에 서버를 맡는 사람이 화면을 눌러
 * 보며 필요한 것을 짐작해야 한다. 짐작은 어긋나고, 어긋난 것은 통합 시점에 드러난다.
 *
 * 그래서 **후속 개발자가 Front-End 화면을 다시 분석하지 않고도 착수할 수 있는 수준**까지
 * 적는다 — 관리 대상 · 데이터 항목 · 관계 · 필요한 연산 · 검증 규칙 · 상태값 · 권한 · 예외.
 *
 * ## 어디까지가 사실인가
 * 데이터 항목은 **화면 명세의 입력 항목을 그대로 읽는다.** 관리자 등록 · 상세 화면의 입력
 * 항목이 곧 그 관리 대상의 속성이기 때문이다. 지어낸 항목을 끼워 넣으면 그것이 그대로
 * 테이블이 된다.
 *
 * 주소 규칙에서 연산을 읽는다 — `/menus` 는 목록, `/menus/[menuId]` 는 단건, `/menus/new` 는
 * 등록. 이 규칙은 화면 등록부가 강제하므로(`spec:check`) 주소를 보고 연산을 말할 수 있다.
 *
 * 엔드포인트는 **확정 사양이 아니라 인터페이스 요구사항**이다. 문서에 그렇게 밝힌다.
 */

