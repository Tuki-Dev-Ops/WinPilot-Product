/**
 * 서비스 운영 규칙 — **주제별로** 모은다.
 *
 * ## 왜 화면별로 적지 않나
 * 처음에는 화면 명세의 운영 정책을 화면 순서대로 늘어놓았다. 그러자 같은 규칙이 여러 화면에
 * 흩어져, "비공개 콘텐츠는 어떻게 되는가" 를 확인하려면 표 전체를 훑어야 했다. 운영 규칙은
 * 화면이 아니라 **주제**로 묻게 된다.
 *
 * ## 무엇을 싣고 무엇을 빼는가
 * 화면 명세의 정책에는 운영 규칙과 구현 메모가 섞여 있다 — `빈 값은 store 의
 * blankFnbNotice() 가 준다` 같은 것은 만드는 사람에게는 중요하지만 발주처가 합의할 대상이
 * 아니다. 여기에는 **운영자와 발주처가 판단해야 하는 것만** 싣는다. 구현 메모는 기능
 * 명세서의 화면별 「처리 규칙」에 그대로 남아 있다.
 *
 * `from` 은 이 규칙을 끌어낸 화면이다. 규칙이 어디서 왔는지 확인할 수 있어야 다툴 때 근거가
 * 된다.
 */
