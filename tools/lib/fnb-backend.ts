/* ── 7.4 API 요구사항 ──────────────────────────────────────── */

export type Endpoint = {
  action: string;
  method: string;
  path: string;
  request: string;
  response: string;
  note: string;
};

const STATUS_FIELD = /공개|노출|고정|상태|감추/;

/**
 * 도메인이 다루는 화면의 주소에서 필요한 연산을 끌어낸다.
 *
 * 손으로 적지 않는 까닭은 늘 같다 — 화면이 하나 늘 때 고칠 곳이 둘이 되면 한쪽만 고친다.
 */
export const endpointsOf = (domain: Domain): Endpoint[] => {
  const screens = domain.screens.map((one) => byId.get(one)).filter((one) => one !== undefined);
  const has = (test: (route: string) => boolean): boolean =>
    screens.some((one) => one.app === 'admin' && test(one.route));

  const single = screens.length === 1 && domain.resource === '/brand';
  const out: Endpoint[] = [];

  if (single) {
    out.push(
      {
        action: '브랜드 정보 조회',
        method: 'GET',
        path: domain.resource,
        request: '없음',
        response: '브랜드 정보 단일 레코드',
        note: '고객 서비스와 관리자 서비스가 함께 사용한다.',
      },
      {
        action: '브랜드 정보 수정',
        method: 'PUT',
        path: domain.resource,
        request: '수정 대상 항목 전체',
        response: '수정된 브랜드 정보',
        note: '삭제 연산은 제공하지 않는다.',
      },
    );
    return out;
  }

  out.push({
    action: '목록 조회',
    method: 'GET',
    path: domain.resource,
    request: '검색어 · 조건 필터 · 정렬 · 페이지',
    response: '목록 및 조건에 걸린 총 건수',
    note: '총 건수는 페이지 구성에 사용한다.',
  });

  if (has((route) => route.includes('['))) {
    out.push({
      action: '단건 조회',
      method: 'GET',
      path: `${domain.resource}/{id}`,
      request: '식별자',
      response: '단건 상세',
      note: '없는 식별자는 404 로 응답한다.',
    });
  }

  if (has((route) => route.endsWith('/new'))) {
    out.push({
      action: '등록',
      method: 'POST',
      path: domain.resource,
      request: '등록 항목 전체',
      response: '생성된 식별자와 단건 상세',
      note: '식별자는 서버가 발급한다.',
    });
  }

  if (has((route) => route.includes('['))) {
    out.push(
      {
        action: '수정',
        method: 'PUT',
        path: `${domain.resource}/{id}`,
        request: '수정 대상 항목 전체',
        response: '수정된 단건 상세',
        note: '변경 항목은 이력에 남긴다.',
      },
      {
        action: '삭제',
        method: 'DELETE',
        path: `${domain.resource}/{id}`,
        request: '식별자',
        response: '처리 결과',
        note: '목록에서 즉시 제외한 뒤 데이터 정책의 파기 기준을 따른다.',
      },
    );
  }

  const source = byId.get(domain.fieldsFrom);
  const statuses = (source?.spec.fields ?? []).filter((one) => STATUS_FIELD.test(one.name));
  for (const one of statuses) {
    out.push({
      action: `${one.name} 상태 변경`,
      method: 'PATCH',
      path: `${domain.resource}/{id}/status`,
      request: `${one.name} 값`,
      response: '변경된 상태',
      note: '노출을 가르는 값이므로 별도 연산으로 둔다.',
    });
  }

  if (domain.resource === '/menu-categories' || domain.resource === '/marketing-channels') {
    return [out[0]!];
  }

  return out;
};

