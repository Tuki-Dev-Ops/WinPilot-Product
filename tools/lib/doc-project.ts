/**
 * 문서 넷이 읽는 **프로젝트 한 벌**.
 *
 * ## 왜 묶었나
 * 문서는 넷이고 프로젝트는 둘이라 파일이 여덟이 된다. 생성기를 프로젝트마다 두면 여덟 벌이
 * 되고, 표 하나를 고치는 일이 여덟 곳을 고치는 일이 된다. 실제로 A4 를 눕히는 결정 하나를
 * 네 곳에 옮겨야 했던 적이 있다 — 그때 한 곳만 고치면 나머지가 세로로 남았다.
 *
 * 그래서 **생성기는 넷, 프로젝트는 둘**로 두고 생성기가 프로젝트를 받는다.
 *
 * ## 무엇이 프로젝트마다 다른가
 * 화면과 명세는 당연히 다르다. 그 밖에 다른 것은 **도입 문장**뿐이다 — 배경 · 목표 · 대상
 * 사용자 · 서비스 역할. 나머지(책임 범위 · 인수 기준 · 변경 관리)는 같은 회사가 같은 방식으로
 * 수행하므로 공용으로 두고, 프로젝트마다 다른 줄만 덧댄다.
 */

