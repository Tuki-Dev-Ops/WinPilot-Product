/**
 * 화면별 **서비스 관점 서술** — 업무 범위 정의서가 읽는다.
 *
 * ## 왜 이 파일만 손으로 적었나
 * 이 저장소의 문서는 전부 생성물이다. 손으로 적으면 화면이 하나 늘 때 고칠 곳이 둘이 되고
 * 실제로는 한쪽만 고치기 때문이다. 그런데 화면 명세는 **만드는 사람끼리 읽는 글**이라
 * `왼쪽 기둥에서 묶음 고르기` 처럼 적혀 있고, 이것을 발주처가 읽는 문장으로 옮기는 일은
 * 어미를 바꾸는 것으로 끝나지 않는다 — `기둥` 이 무엇을 가리키는지 알아야 `카테고리 목록`
 * 이라고 쓸 수 있다.
 *
 * 기계로 옮기면 `묶음 고릅니다` 가 되어 여전히 작업 지시문이다. 그래서 여기만 사람이 적는다.
 *
 * ## 그래도 어긋남은 잡는다
 * 항목마다 `from` 에 **적을 당시의 세부 기능 수**를 남긴다. 명세의 기능이 늘거나 줄면 생성기가
 * 그 화면을 짚어 알려 준다. 손으로 적은 글이 조용히 낡는 것을 막으려는 장치다.
 *
 * `features` 의 줄 수는 `from` 과 같지 않아도 된다. `매장명으로 검색` 과 `주소로 검색` 은
 * 한 기능이고, 실제로 한 줄로 적는 편이 읽힌다.
 *
 * ## 지키는 것
 * 기능 ID · 화면명 · 메뉴 경로 · 화면 경로는 여기서 손대지 않는다 — 전부 화면 등록부에서
 * 온다. 원본에 없는 기능을 새로 만들지 않는다. 원본의 기능을 빼지 않는다.
 */

