/**
 * 화면 명세의 기능 한 줄을 **동작 유형**으로 가른다.
 *
 * ## 왜 필요한가
 * 명세는 "왜 이 기능이 있는가" 를 적는다 — `메뉴 카드 열기`. 기능 명세서는 "사용자가 무엇을
 * 하면 시스템이 어떻게 처리하고 무엇이 남는가" 를 적어야 한다. 그 사이를 잇는 것이 동작
 * 유형이다. 여는 동작은 언제나 대상 화면을 열고, 거르는 동작은 언제나 목록을 다시 거른다.
 *
 * ## 지어내는 것과 끌어내는 것
 * 화면 명세에 단추가 적혀 있으면 **그것이 이긴다** — 눌렀을 때 · 성공했을 때 · 실패했을 때가
 * 명세에 있는 값이기 때문이다. 단추가 없는 기능만 유형에서 끌어낸다.
 *
 * 끌어낸 것은 확정이 아니다. 문서에 그렇게 밝혀 두고, 유형을 못 가른 것은 `정의 필요` 로
 * 남긴다. 애매한 것을 그럴듯하게 채우면 검토하는 사람이 그것을 합의된 값으로 읽는다.
 *
 * ## 차례가 규칙이다
 * 먼저 걸리는 것이 이긴다. `매장 찾기로 이동` 은 `찾기` 도 `이동` 도 들어 있지만 이동이다.
 * 그래서 이동을 맨 앞에 둔다.
 */

export type ActionKind = '이동' | '검색' | '필터' | '등록' | '수정' | '삭제' | '상태 변경' | '표시' | '미분류';

const RULES: [RegExp, ActionKind][] = [
  [/이동|열기|열린|연다|들어가|바로가|돌아가|넘어가|으로$|로$/, '이동'],
  [/검색|찾아/, '검색'],
  [/고르기|고른|거르|가리기|추리|좁히|묶음별|필터/, '필터'],
  /* 상태 변경이 수정보다 앞이다 — `하루 감추기 정하기` 는 값을 고치는 것이 아니라 노출을 가른다. */
  [/켜기|끄기|공개|비공개|노출|고정|해제|상태|감추/, '상태 변경'],
  [/지우|삭제|빼기|없애/, '삭제'],
  [/등록|넣기|추가|올리기|신청|접수|만들기|남기기|보내기|채우기|쓰기|동의/, '등록'],
  [/고치|수정|바꾸|편집|덮어|정하기/, '수정'],
  [/확인|읽|보기|펼치|접기|훑|살피|비교|누르기|당기기/, '표시'],
];

export const kindOf = (action: string): ActionKind =>
  RULES.find(([test]) => test.test(action))?.[1] ?? '미분류';

