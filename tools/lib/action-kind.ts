/**
 * 세부 기능 절의 갈래. 이동과 표시는 조회 흐름에 묶는다 — 받은 양식이 일곱 갈래이고,
 * 그 안에 화면 이동만을 위한 자리는 없다.
 */
export const SECTION_OF: Record<ActionKind, string> = {
  이동: '조회',
  표시: '조회',
  검색: '검색',
  필터: '필터',
  등록: '등록',
  수정: '수정',
  삭제: '삭제',
  '상태 변경': '상태 변경',
  미분류: '정의 필요',
};

export const SECTION_ORDER = ['조회', '검색', '필터', '등록', '수정', '삭제', '상태 변경', '정의 필요'];

/**
 * 화면 성격을 함께 보고 동작 유형을 정한다.
 *
 * 낱말만으로는 갈리지 않는 것이 있다. 같은 `고르기` 가 목록에서는 거르개이고 입력 화면에서는
 * 값을 채우는 일이다 — `알레르기 고르기` 를 필터로 두면 "목록을 다시 거른다" 라는 처리가
 * 붙어, 사실과 다른 명세가 된다.
 *
 * 읽기만 하는 화면에는 이 되돌림을 걸지 않는다. 그쪽의 `고르기` 는 언제나 거르개다.
 */
export const kindIn = (action: string, route: string, readOnly: boolean): ActionKind => {
  const kind = kindOf(action);
  if (readOnly) return kind;
  const isForm = route.endsWith('/new') || route.includes('[');
  if (!isForm) return kind;
  if (kind === '필터' || kind === '수정') return route.endsWith('/new') ? '등록' : '수정';
  return kind;
};

/** 세부 기능이 들어갈 절. 유형이 정해지면 절은 따라온다. */
export const sectionOf = (kind: ActionKind): string => SECTION_OF[kind];

/**
 * 조건이 붙은 문장을 **IF / THEN** 으로 가른다.
 *
 * 명세의 제약과 정책은 대개 `…없으면 …하지 않는다` 꼴이라 조건과 처리가 한 문장에 있다.
 * 나눌 수 있는 것만 나누고, 표지가 없으면 통째로 처리로 둔다 — 없는 조건을 지어내면 그것이
 * 검수 기준이 되어 버린다.
 */
export const condition = (sentence: string): { when: string | null; then: string } => {
  /*
    표지를 `면` 하나로 두었더니 `화면` 의 `면` 이 걸려 "…대신 화면 / 위쪽에 적는다" 로
    갈라졌다. 조건을 만드는 어미만 적는다.

    찾는 자리도 첫 문장 안으로 묶는다. 문장을 넘어가면 앞 문장 전체가 조건절로 딸려 와,
    "…세우지 않는다. 눌렀을 때 빈 화면이 나오면" 이 통째로 IF 가 된다.
  */
  const match =
    /^([^.!?]*?(?:(?<!화|장|지|측|반|표|국|전|후|수|노|단|양)면|을 때|인 경우|는 경우|일 경우))\s+(.+)$/s.exec(
      sentence,
    );
  if (!match) return { when: null, then: sentence };
  const [, when, then] = match;
  return { when, then };
};
