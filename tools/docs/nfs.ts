/**
 * 비기능 명세(NFS) — **화면을 가리지 않고 걸리는 정책**을 모은다.
 *
 * 화면마다 되풀이해 적으면 한 곳만 고쳐졌을 때 어느 쪽이 맞는지 알 수 없다. 여기 한 장에
 * 두고 화면 명세는 그 화면만의 조건을 적는다.
 *
 * 아직 쓰지 않는 것(업로드·전역 검색 같은 것)도 **"현재 미사용" 이라고 적고 기준은 정해 둔다.**
 * 기준이 없으면 나중에 필요해진 사람이 그 자리에서 즉흥으로 정하고, 그때부터 두 벌이 된다.
 */
export type NfsApp = {
  dir: string;
  label: string;
  /** 이 앱이 쓰는 너비 */
  breakpoints: Array<{ label: string; width: number }>;
};

export type Policy = {
  /** 파일 이름 — 주소는 소문자로 내려간다 */
  file: string;
  title: string;
  purpose: string;
  scope: string;
  policy: string[];
  rules: { head: string[]; rows: string[][] };
  exceptions: string[];
  checklist: string[];
};

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

const list = (items: string[]) => items.map((item) => `- ${item}`).join('\n');
const checks = (items: string[]) => items.map((item) => `- [ ] ${item}`).join('\n');

function policyDoc(app: NfsApp, policy: Policy): string {
  return `# ${policy.title}

> ${app.label} · 생성: \`pnpm docs:build\` · 원본: \`tools/docs/nfs.ts\`

## 목적

${policy.purpose}

## 적용 범위

${policy.scope}

## 정책

${list(policy.policy)}

## 세부 기준

${table(policy.rules.head, policy.rules.rows)}

## 예외

${list(policy.exceptions)}

## 점검 항목

${checks(policy.checklist)}
`;
}

