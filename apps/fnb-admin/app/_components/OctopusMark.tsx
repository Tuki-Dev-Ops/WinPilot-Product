/**
 * 문어 실루엣 — **사진이 오기 전까지 그 자리에 서는 그림.**
 *
 * ## 왜 그려서 쓰나
 * 사진이 없다. 무료 사진을 받아 쓰면 **다른 집 문어**가 이 브랜드의 얼굴로 서고, 나중에 진짜
 * 사진이 들어와도 그 인상이 먼저 남는다. 그렇다고 글자 한 자만 두면 화면이 덜 만들어진 것처럼
 * 보였다(전에 그랬다).
 *
 * 그려 두면 셋 다 피한다 — 남의 것이 아니고, 비어 보이지 않고, **무엇을 파는 집인지**가 한눈에
 * 드러난다. 진짜 사진이 들어오는 날 이 조각을 쓰는 자리(`PhotoSlot`) 하나만 고치면 된다.
 *
 * ## 다리를 여덟 개 그리지 않는다
 * 실제 문어는 여덟이다. 그런데 작은 칸에서 여덟을 그리면 다리가 겹쳐 **덩어리 하나**로 뭉개진다.
 * 앞으로 보이는 다섯만 그린다 — 실루엣에서 세는 사람은 없고, 다섯이면 굵기가 살아난다.
 *
 * ## 눈을 크게, 하나만 진하게
 * 이름이 `어쭈구리` 다. 장난스러운 이름에 실물 그대로의 문어를 두면 말과 그림이 어긋난다.
 * 눈을 크게 두면 그림이 이름을 따라간다.
 *
 * ## 사이트 것과 두 벌이다
 * `apps/fnb-client-a` 에 같은 파일이 있다. 공유 패키지(`@winpilot/ui`)는 **자기가 무엇을 담는지
 * 모르는** 자리라(그 패키지 머리말) 특정 브랜드의 그림이 거기 살 수 없고, 두 앱이 나눠 쓸 다른
 * 자리는 아직 없다.
 *
 * 알고 두는 두 벌이다. 로고 원본 파일을 받는 날 둘 다 사라진다 — 그때는 `BrandMark` 가 파일을
 * 쓰므로 `mark` 를 넘기던 두 줄만 지우면 된다.
 *
 * ## 색을 물려받는다
 * `currentColor` 로 그려서 부르는 쪽이 색과 흐림을 정한다. 값으로 박아 두면 어두운 판과 밝은
 * 판에 각각 한 벌씩 필요해진다.
 */
export function OctopusMark({ className = '' }: { className?: string }) {
  return (
    <svg
      aria-hidden
      viewBox="0 0 120 120"
      fill="none"
      className={className}
      xmlns="http://www.w3.org/2000/svg"
    >
      {/* 머리 — 아래가 넓은 둥근 종 모양. 문어를 문어로 보이게 하는 것은 이 실루엣이다. */}
      <path
        d="M60 16c-19 0-33 14-33 32 0 10 4 17 9 22 3 3 4 5 4 8h40c0-3 1-5 4-8 5-5 9-12 9-22 0-18-14-32-33-32z"
        fill="currentColor"
      />

      {/*
        다리 다섯. 끝으로 갈수록 가늘어지게 `stroke-width` 를 나눠 그린다 — 한 굵기로 그으면
        고무호스처럼 보인다. `round` 끝맺음이 그 가늘어짐을 이어 준다.
      */}
      <g stroke="currentColor" strokeLinecap="round" fill="none">
        <path d="M34 78c-6 8-10 12-18 14" strokeWidth="9" />
        <path d="M46 80c-3 10-6 16-12 21" strokeWidth="10" />
        <path d="M60 82c0 11 1 17 4 23" strokeWidth="11" />
        <path d="M74 80c3 10 7 16 13 20" strokeWidth="10" />
        <path d="M86 78c6 8 11 12 19 13" strokeWidth="9" />
      </g>

      {/*
        눈은 바탕색으로 뚫는다. 흰색을 칠하면 어두운 판 위에서 눈만 하얗게 떠 보인다 —
        `currentColor` 로 그린 그림에서 구멍은 **안 그리는 것**으로 만든다.
      */}
      <g fill="var(--color-canvas)">
        <circle cx="47" cy="45" r="7" />
        <circle cx="73" cy="45" r="7" />
      </g>
      <g fill="currentColor">
        <circle cx="49" cy="46" r="3.2" />
        <circle cx="75" cy="46" r="3.2" />
      </g>
    </svg>
  );
}
