/**
 * 화면별 명세 — **기능과 비기능을 한 자리에서** 적는다.
 *
 * 마크다운 한 장에 26개 화면을 모두 적지 않는다. 그러면 한 화면을 고칠 때마다 긴 문서를 훑어야
 * 하고, 어느 화면의 명세가 비어 있는지도 보이지 않는다. 화면 하나가 항목 하나다.
 *
 * `screen` 은 `pages.manifest.ts` 의 `id` 와 같다 — 매니페스트에 있는데 여기 없으면
 * `missingSpecs()` 가 알려 준다. 문서가 화면을 따라가지 못하는 것을 사람이 기억하지 않는다.
 *
 * ## 어드민 연동
 * - 각 항목의 `admin` 이 그 화면이 읽는 어드민 화면이다. 자세한 표는 `/admin-sync`.
 */
/** 화면 구성 — 어떤 영역이 왜 있고 언제 보이는가 (FSD §3) */
export type SpecArea = { area: string; purpose: string; when?: string };

/** 입력·출력 항목 (FSD §4) */
export type SpecField = {
  name: string;
  desc: string;
  /** 입력 형태 — 읽기만 하는 값이면 `표시` */
  type: string;
  required?: boolean;
  /** 형식·길이·범위 */
  rule?: string;
  example?: string;
};

/** 단추와 그 결과 (FSD §6) */
export type SpecButton = {
  label: string;
  /** 눌렀을 때 */
  onClick: string;
  /** 성공했을 때 — 화면이 어떻게 바뀌는가 */
  onSuccess?: string;
  /** 실패했을 때 */
  onFail?: string;
};

export type ScreenSpec = {
  /** `pages.manifest.ts` 의 id */
  screen: string;
  /** 이 화면이 있는 이유 — 한 문장 */
  purpose: string;
  /**
   * 이 화면이 왜 생겼는가 — **목적보다 앞의 이야기**.
   *
   * `purpose` 는 이 화면이 지금 무엇을 하는지를 적고, 여기는 **그 화면이 없던 때 무엇이
   * 불편했는지**를 적는다. 둘을 한 칸에 쓰면 목적이 길어지면서 "무엇을 하는가" 가 흐려진다.
   *
   * 없어도 된다. 배경이 특별할 것 없는 화면(약관 · 개인정보처럼 법이 요구해서 있는 화면)에
   * 억지로 쓰면 지어낸 이야기가 남는다 — 그럴 바에는 비워 두는 편이 낫다.
   */
  background?: string;
  /** 이 화면을 두어서 얻는 것 — 없으면 목적에서 끌어 쓴다 */
  effect?: string;
  /** 할 수 있는 일 */
  actions: string[];
  /** 막는 것과 그때 나오는 말 */
  guards: string[];
  /** 값이 오는 어드민 화면 */
  admin: string[];
  /** 판정 가능한 비기능 조건 */
  nonFunctional: string[];

  /*
    아래는 기획 명세(FSD)를 채우는 항목이다. 적지 않으면 생성기가 그 절을 `N/A` 로 적는다 —
    비워 두는 것과 "해당 없음" 은 다르고, 읽는 사람은 그 둘을 구분할 수 없기 때문이다.
  */
  areas?: SpecArea[];
  fields?: SpecField[];
  buttons?: SpecButton[];
  /** 입력값을 거르는 규칙 (FSD §9) */
  validations?: string[];
  /** 기본 정렬·검색·페이징·조건 유지 (FSD §12) */
  policy?: string[];
  /** 앞으로 늘어날 방향 (FSD §14) */
  future?: string[];
};

