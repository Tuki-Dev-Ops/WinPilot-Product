/**
 * 화면별 명세 — 사내 어드민.
 *
 * 다른 두 앱의 명세와 **같은 모양**을 쓴다(`apps/b2c-admin/lib/screen-specs.ts`).
 * 앱마다 명세 구조가 다르면 같은 항목을 서로 다른 이름으로 찾게 되고, 생성기도 세 벌이 된다.
 *
 * 방향만 다르다. 고객 화면의 `admin` 은 **값을 받아 오는 곳**, 어드민의 `admin` 은 그 값이
 * **나타나는 고객 화면**이고, 여기 `admin` 은 이 콘솔이 정한 값이 반영되는 **고객사의 배포**다.
 * 어느 쪽이 원본인지 문서에서 갈려야 한다.
 *
 * `screen` 은 `pages.manifest.ts` 의 `id` 와 같다.
 */
export type SpecArea = { area: string; purpose: string; when?: string };

export type SpecField = {
  name: string;
  desc: string;
  type: string;
  required?: boolean;
  rule?: string;
  example?: string;
};

export type SpecButton = { label: string; onClick: string; onSuccess?: string; onFail?: string };

export type ScreenSpec = {
  screen: string;
  purpose: string;
  /**
   * 이 화면이 왜 생겼는가 — **목적보다 앞의 이야기**.
   *
   * `purpose` 는 이 화면이 지금 무엇을 하는지를 적고, 여기는 **그 화면이 없던 때 무엇이
   * 불편했는지**를 적는다. 둘을 한 칸에 쓰면 목적이 길어지면서 "무엇을 하는가" 가 흐려진다.
   *
   * 없어도 된다. 배경이 특별할 것 없는 화면(약관 · 개인정보처럼 법이 요구해서 있는 화면)에
   * 억지로 쓰면 지어낸 이야기가 남는다 — 그럴 바에는 비워 두는 편이 낫다.
   */
  background?: string;
  effect?: string;
  actions: string[];
  guards: string[];
  /** 이 화면이 정한 값이 반영되는 고객사의 배포 */
  admin: string[];
  nonFunctional: string[];
  areas?: SpecArea[];
  fields?: SpecField[];
  buttons?: SpecButton[];
  validations?: string[];
  policy?: string[];
  future?: string[];
};

