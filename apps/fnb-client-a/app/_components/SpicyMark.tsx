import { Flame } from 'lucide-react';

/**
 * 매운 정도 — **불꽃 개수로 말한다.**
 *
 * ## 왜 글자가 아닌가
 * `매운맛` 이라는 말은 맵다는 것만 말하고 얼마나 매운지는 말하지 않는다. `매운맛 3단계` 라고
 * 적으면 말하기는 하는데, 카드 사진 위의 작은 딱지에 여섯 글자가 들어가면 다른 표(`인기`)와
 * 길이가 어긋나 줄이 들쭉날쭉해진다.
 *
 * 불꽃은 **세는 것**이라 한눈에 견줘진다 — 둘과 셋의 차이를 읽지 않고 본다.
 *
 * ## 못 채운 자리를 비워 두지 않는다
 * 세 개를 늘 그리고 안 매운 만큼을 흐리게 두는 방법도 있다. 그러면 1단계가 **셋 중 하나**로
 * 읽혀 정확한데, 딱지가 늘 세 개 폭이라 1단계 메뉴에서 자리를 두 칸 낭비한다. 카드 위에
 * 얹히는 딱지는 작을수록 사진을 덜 가리므로 채운 것만 그린다.
 *
 * ## 낭독기에는 숫자로 말한다
 * 불꽃 셋을 읽어 주면 `불꽃 불꽃 불꽃` 이 된다. 그림은 숨기고 딱지 자체가 `매운맛 3단계` 라는
 * 이름을 갖는다.
 *
 * ## 사진 위 딱지가 검지 않다 — 희다
 * 한때 검은 딱지(`bg-night/80`)에 붉은 불꽃이었다. 붉은색이 어두운 바탕에서 **가라앉아**, 옆에
 * 선 `인기` 표(채운 빨강)보다 뒤로 물러나 보였다 — 정작 더 급한 정보인데.
 *
 * 흰 딱지로 바꾸니 붉은 불꽃이 제 색으로 선다. 옆의 `인기` 와도 갈린다(하나는 채운 적갈, 하나는
 * 흰 바탕에 적갈) — 두 딱지가 같은 색이면 나란히 섰을 때 한 덩이로 읽힌다.
 *
 * 불꽃도 브랜드색이다. 경고색(`signal-danger`)을 쓰면 매운 것이 **위험한 것**으로 읽히고,
 * 무엇보다 그 색은 이 사이트에서 잘못됐다는 뜻으로 따로 남겨 둔다. 맵다는 것은 불꽃 모양이
 * 이미 말하고 있어 색까지 경고일 필요가 없다.
 *
 * 흰색을 값으로 고정하는 이유: 이 딱지는 **사진 위에** 얹힌다. `bg-canvas` 같은 토큰을 쓰면
 * 어두운 화면에서 딱지가 다시 어두워지는데, 사진은 화면 설정을 따라 바뀌지 않는다.
 *
 * 아주 옅은 테두리(`ring`)를 두르는 것은 흰 사진 위에서 딱지 가장자리가 사라지지 않게 하려는
 * 것이다 — 그림자를 쓰면 작은 딱지에서 번져 보인다.
 */
export function SpicyMark({ level, tone = 'overlay' }: { level: 1 | 2 | 3; tone?: 'overlay' | 'plain' }) {
  return (
    <span
      aria-label={`매운맛 ${level}단계`}
      className={`flex shrink-0 items-center gap-0.5 rounded-full px-2 py-1 ${
        tone === 'overlay' ? 'bg-white ring-1 ring-night/10' : 'border border-border'
      }`}
    >
      {Array.from({ length: level }, (_, at) => (
        <Flame
          key={at}
          aria-hidden
          /* 채운 불꽃이라 테두리가 아니라 면으로 그린다 — 작은 크기에서는 선이 뭉개진다. */
          className="size-3.5 shrink-0 fill-octo-500 stroke-octo-500"
          strokeWidth={1.5}
        />
      ))}
    </span>
  );
}
