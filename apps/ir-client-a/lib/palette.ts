/**
 * 어두운 칸의 색 — **CSS 클래스로 줄 수 없는 자리**를 위한 값.
 *
 * ## 왜 토큰이 아니라 여기인가
 * 색의 원본은 `@winpilot/tokens` 다. 화면에서 색을 줄 때는 언제나 그쪽 클래스를 쓴다
 * (`bg-night` · `text-ink-muted` …).
 *
 * 그런데 **SVG 안**은 사정이 다르다. `fill` · `stroke` 는 클래스가 아니라 속성으로 받고, 값도
 * 반투명이 섞인다(`rgba(...)`). Tailwind 로는 `fill-[rgba(148,163,184,0.24)]` 처럼 쓸 수야
 * 있지만, 그러면 **같은 회색이 스무 자리에 스무 번 적히고** 그중 하나만 0.25 로 어긋나도
 * 아무도 알아채지 못한다.
 *
 * 그래서 SVG 가 쓰는 색만 여기 모은다. 여기 없는 색을 화면에서 직접 적는 일은 없어야 한다.
 *
 * ## 알파를 섞지 않고 미리 섞은 값을 두는 이유
 * 켜진 방의 벽·기계는 **불투명**해야 한다. 반투명으로 두면 그 너머의 무대 선과 뒤쪽 방이
 * 비쳐 유리로 지은 공장처럼 보인다. 그래서 `LIT` 은 `NIGHT` 에 파랑을 미리 섞은 색이다 —
 * 눈에 보이는 색은 알파를 준 것과 같고, 뒤엣것만 가려진다.
 */

/** 어두운 칸의 바탕. 토큰 `--color-night` 과 **같은 값**이다(그쪽은 클래스로 쓰는 자리). */
export const NIGHT = '#05060d';

/** 아이소메트릭 도형의 면 색. */
export type IsoTone = {
  /** 윗면 */ top: string;
  /** 오른쪽 면 — 빛이 드는 쪽이라 조금 밝다 */ right: string;
  /** 왼쪽 면 */ left: string;
  /** 모서리 */ line: string;
};

/** 꺼진 방. */
export const DIM: IsoTone = {
  top: '#0e1621',
  right: '#0a111a',
  left: '#070c13',
  line: 'rgba(148,163,184,0.24)',
};

/**
 * 켜진 방 — 브랜드 파랑.
 *
 * 참고한 화면은 청록이지만 그 색은 이 저장소에 없다. 여기 한 곳에만 새 색을 들이면 그 값이
 * 토큰 밖에서 자라기 시작한다.
 */
export const LIT: IsoTone = {
  top: '#14294d',
  right: '#0e1c36',
  left: '#0a1324',
  line: 'rgba(138,186,255,0.9)',
};

/** 스스로 빛나는 면 — 창 · 화면 · 표시등. 알파를 쓰지 않는 이유는 위 머리말과 같다. */
export function glowOf(lit: boolean): string {
  return lit ? '#7ba7e8' : '#1d2531';
}

/** 선으로만 그리는 것 — 팔의 마디 · 난간 · 배선. */
export function lineOf(lit: boolean): string {
  return lit ? 'rgba(215,232,255,0.9)' : 'rgba(148,163,184,0.5)';
}

/** 밝은 파랑 한 톤. 불빛·표시등·눈처럼 **가장 밝아야 하는 점**에 쓴다. */
export const SPARK = '#cfe4ff';

/** 무대 바닥이 쓰는 회색들. 옅은 차례대로 — 살 · 테두리 · 길. */
