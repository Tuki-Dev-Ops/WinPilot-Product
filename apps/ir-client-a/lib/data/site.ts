/**
 * 회사 홈페이지의 값 — **아직 어드민이 다루지 않는 것들**.
 *
 * 공시·재무·주주는 `ir-admin` 이 올리고 `@winpilot/store` 가 원본을 갖는다. 여기 있는 것은
 * 그 밖의 값이다 — 솔루션 소개 · 특허 · FAQ · 오시는 길.
 *
 * ## 왜 아직 store 가 아닌가
 * 올리는 화면이 없기 때문이다. 값을 공유 패키지에 올려 두면 **두 앱이 읽는 것처럼 보이는데
 * 한쪽에는 그 화면이 없다** — 어드민에서 고칠 수 없는 값이 store 에 있으면, 고치려는 사람이
 * 없는 화면을 찾게 된다.
 *
 * ## 서비스·솔루션·미디어는 옮겼다
 * IR 어드민에 홈페이지 갈래(`/site/*`)가 생긴 날, 위 규칙에 따라 `@winpilot/store` 의
 * `site.ts` 로 갔다. 여기 남은 것은 아직 올리는 화면이 없는 것들이다 — 특허·FAQ·오시는 길.
 *
 * 연혁만은 예외다. `@winpilot/store` 의 `MILESTONES` 를 그대로 읽는다 — B2C 어드민의 회사 >
 * 연혁이 이미 그 값을 고치고 있어, 여기에 따로 두면 같은 회사의 연혁이 두 벌이 된다.
 */

